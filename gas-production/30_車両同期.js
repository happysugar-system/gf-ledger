/** 車検表示：通常予定を優先し、通常予定なしの場合は台帳の満了日を表示。 */
function 予定管理から次の予定を取得する_(VehicleID) {
  const next=GF_通常の次の予定を取得する_30(VehicleID);
  if(next.予定)return next;
  const ss=対象スプレッドシートを開く_();
  const ledger=必須シートを取得する_(ss,シート名.車両台帳);
  const row=IDで行を探す_(ledger,'VehicleID',VehicleID);
  if(!row)return next;
  const expiry=GF_車検日付を解析する_30(行データを取得する_(ledger,row)['車検満了日']);
  if(!expiry)return next;
  const expired=GF_車検注意を判定する_30(expiry)==='⚠ 車検満了（期限超過）';
  return {予定:expired?'⚠ 車検満了（期限超過）':'車検満了',日付:expiry};
}
function GF_車検日付を解析する_30(value) {
  if(!value)return null;
  if(value instanceof Date)return isNaN(value.getTime())?null:new Date(value.getTime());
  const m=String(value).trim().match(/^(\d{4})[年\/.-](\d{1,2})[月\/.-](\d{1,2})日?$/);
  if(!m)return null;
  const y=Number(m[1]),mo=Number(m[2]),day=Number(m[3]);
  const d=new Date(y,mo-1,day,12);
  return d.getFullYear()===y&&d.getMonth()===mo-1&&d.getDate()===day?d:null;
}
function GF_車検注意を判定する_30(value,now) {
  const d=GF_車検日付を解析する_30(value);if(!d)return '';
  const tz=Session.getScriptTimeZone();
  const dateKey=x=>Utilities.formatDate(x,tz,'yyyy-MM-dd');
  const today=dateKey(now||new Date()),expiry=dateKey(d);
  if(expiry<today)return '⚠ 車検満了（期限超過）';
  // 満了日の1・2暦月前。同じ日がない月はその月末を使う。
  const p=expiry.split('-').map(Number);
  const before=months=>{
    const first=new Date(p[0],p[1]-1-months,1,12);
    const last=new Date(first.getFullYear(),first.getMonth()+1,0,12).getDate();
    return dateKey(new Date(first.getFullYear(),first.getMonth(),Math.min(p[2],last),12));
  };
  if(today>=before(1))return '⚠ 車検満了まで1か月以内';
  if(today>=before(2))return '⚠ 車検満了まで2か月以内';
  return '';
}
function GF_車検注意列を準備する_30(sheet) {
  const heads=sheet.getRange(1,1,1,sheet.getLastColumn()).getDisplayValues()[0].map(x=>String(x||'').trim());
  let col=heads.indexOf('⚠ 注意事項')+1;
  if(!col){col=heads.length+1;if(col>sheet.getMaxColumns())sheet.insertColumnAfter(sheet.getMaxColumns());sheet.getRange(1,col).setValue('⚠ 注意事項');}
  return col;
}
function GF_車検注意の色を設定する_30(sheet) {
  const 注意列 = GF_車検注意列を準備する_30(sheet);

  const headers = sheet
    .getRange(1, 1, 1, sheet.getLastColumn())
    .getDisplayValues()[0]
    .map(v => String(v || '').trim());

  const 満了列 = headers.indexOf('車検満了日') + 1;

  if (!満了列) {
    throw new Error('車両状況に「車検満了日」列がありません。');
  }

  const 行数 = Math.max(1, sheet.getMaxRows() - 1);
  const 注意範囲 = sheet.getRange(2, 注意列, 行数, 1);
  const 満了範囲 = sheet.getRange(2, 満了列, 行数, 1);

  const 列記号 = sheet
    .getRange(1, 注意列)
    .getA1Notation()
    .replace(/\d+$/, '');

  const 文言 = [
    '⚠ 車検満了（期限超過）',
    '⚠ 車検満了まで1か月以内',
    '⚠ 車検満了まで2か月以内'
  ];

  const 色 = [
    ['#f4cccc', '#990000'],
    ['#fce5cd', '#b45f06'],
    ['#fff2cc', '#7f6000']
  ];

  const 数式 = 文言.map(
    text => '=$' + 列記号 + '2="' + text + '"'
  );

  // 今回の車検色ルールだけ入れ替える。
  const 既存 = sheet.getConditionalFormatRules().filter(rule => {
    const 条件 = rule.getBooleanCondition();
    if (!条件) return true;

    const 種類 = 条件.getCriteriaType();
    const 値 = String(条件.getCriteriaValues()[0] || '');

    const 対象列 = rule.getRanges().some(r =>
      r.getNumColumns() === 1 &&
      [注意列, 満了列].includes(r.getColumn())
    );

    const 車検ルール =
      (
        種類 === SpreadsheetApp.BooleanCriteria.TEXT_EQUAL_TO &&
        文言.includes(値)
      ) ||
      (
        種類 === SpreadsheetApp.BooleanCriteria.CUSTOM_FORMULA &&
        数式.includes(値)
      );

    return !(対象列 && 車検ルール);
  });

  const 新規 = 数式.map((formula, i) =>
    SpreadsheetApp.newConditionalFormatRule()
      .whenFormulaSatisfied(formula)
      .setBackground(色[i][0])
      .setFontColor(色[i][1])
      .setRanges([注意範囲, 満了範囲])
      .build()
  );

  sheet.setConditionalFormatRules(新規.concat(既存));
}
/** 初回に一度実行。既存車両を更新し、日付変更用の毎日トリガーを設定する。 */
function GF_車検注意表示を初期設定する() {
  const ss = 対象スプレッドシートを開く_();
  const 状況 = 必須シートを取得する_(ss, シート名.車両状況);

  // 色分けを先に設定する。
  GF_車検注意の色を設定する_30(状況);

  const 毎日関数 = 'GF_車検注意表示を毎日更新する';
  const 再試行関数 = 'GF_車検注意表示を再試行する';

  ScriptApp.getProjectTriggers().forEach(t => {
    if ([毎日関数, 再試行関数].includes(t.getHandlerFunction())) {
      ScriptApp.deleteTrigger(t);
    }
  });

  ScriptApp.newTrigger(毎日関数)
    .timeBased()
    .everyDays(1)
    .atHour(0)
    .nearMinute(15)
    .inTimezone(Session.getScriptTimeZone())
    .create();

  // 更新中だった場合も、後から自動で再試行する。
  ScriptApp.newTrigger(再試行関数)
    .timeBased()
    .everyMinutes(1)
    .create();

  console.log('色分け・毎日更新・再試行を設定しました。');

  GF_車検注意表示を再試行する();
}

function GF_車検注意表示を再試行する() {
  try {
    GF_車検注意表示を毎日更新する();

  } catch (error) {
    const message = String(error && error.message || error);

    if (message.includes('更新中です')) {
      console.log(
        '他の同期処理が更新中です。約1分後に自動で再試行します。'
      );
      return;
    }

    // 列不足など、待っても解決しないエラーは表示する。
    throw error;
  }

  // 更新が完了したら、再試行トリガーを削除する。
  ScriptApp.getProjectTriggers().forEach(t => {
    if (
      t.getHandlerFunction() ===
      'GF_車検注意表示を再試行する'
    ) {
      ScriptApp.deleteTrigger(t);
    }
  });

  console.log('車検表示の更新が完了しました。再試行を終了します。');
}
function GF_車検注意表示を毎日更新する() {
  const lock = LockService.getScriptLock();

  if (!lock.tryLock(10000)) {
    throw new Error('更新中です。少し待ってから再実行してください。');
  }

  try {
    const ss = 対象スプレッドシートを開く_();
    const 台帳 = 必須シートを取得する_(ss, シート名.車両台帳);
    const 状況 = 必須シートを取得する_(ss, シート名.車両状況);
    const 予定 = ss.getSheetByName(シート名.予定管理);

    GF_車検注意列を準備する_30(状況);

    const 読込 = sheet => {
      if (!sheet) return { 列: {}, 行: [] };

      const values = sheet.getDataRange().getValues();
      const 列 = {};

      (values.shift() || []).forEach((v, i) => {
        列[String(v || '').trim()] = i;
      });

      return { 列: 列, 行: values };
    };

    const 車 = 読込(台帳);
    const 表示 = 読込(状況);
    const イベント = 読込(予定);

    const 列確認 = (data, names, sheetName) => {
      names.forEach(name => {
        if (data.列[name] === undefined) {
          throw new Error(sheetName + 'に「' + name + '」列がありません。');
        }
      });
    };

    列確認(車, ['VehicleID', '車検満了日'], '車両台帳');
    列確認(
      表示,
      ['VehicleID', '次の予定', '次の予定日', '車検満了日', '⚠ 注意事項'],
      '車両状況'
    );

    if (イベント.行.length) {
      列確認(
        イベント,
        ['VehicleID', '状態', '予定日', '予定種類名'],
        '予定管理'
      );
    }

    const ID = v => String(v || '').trim();
    const 今 = new Date();
    const tz = Session.getScriptTimeZone();
    const 日付キー = d => Utilities.formatDate(d, tz, 'yyyy-MM-dd');
    const 今日 = 日付キー(今);
    const 車索引 = new Map();
    const 予定索引 = new Map();

    車.行.forEach(r => {
      const id = ID(r[車.列.VehicleID]);
      if (id) 車索引.set(id, r);
    });

    イベント.行.forEach(r => {
      const h = イベント.列;
      const id = ID(r[h.VehicleID]);
      const 状態 = ID(r[h['状態']]);
      const 名前 = ID(r[h['予定種類名']]);

      if (!id || !['予定', '進行中'].includes(状態) || !名前) return;

      if (
        名前 === '車検満了' ||
        ID(r[h['予定種類ID']]) === 'GF_VEHICLE_INSPECTION_EXPIRY'
      ) return;

      const 日付 = GF_車検日付を解析する_30(r[h['予定日']]);
      if (!日付) return;

      const key = 日付キー(日付);
      if (key < 今日 && 状態 !== '進行中') return;

      const 前 = 予定索引.get(id);

      if (!前 || key < 前.key) {
        予定索引.set(id, {
          予定: 名前,
          日付: 日付,
          key: key
        });
      }
    });

    console.log(
      '一括読込完了：台帳' + 車.行.length +
      '行／車両状況' + 表示.行.length +
      '行／予定' + イベント.行.length + '行'
    );

    if (!表示.行.length) {
      console.log('更新対象なし');
      return;
    }

    const 列名 = [
      '次の予定',
      '次の予定日',
      '車検満了日',
      '⚠ 注意事項'
    ];

    // 対象外の行は元の値・数式を保持する。
    const 書込列 = 列名.map(name => {
      const col = 表示.列[name] + 1;
      const 数式 = 状況
        .getRange(2, col, 表示.行.length, 1)
        .getFormulas();

      return 表示.行.map((r, i) => [
        数式[i][0] || r[col - 1]
      ]);
    });

    let 件数 = 0;

    表示.行.forEach((r, i) => {
      const id = ID(r[表示.列.VehicleID]);
      const car = 車索引.get(id);
      if (!car) return;

      const 元満了日 = car[車.列['車検満了日']];
      const 満了日 = GF_車検日付を解析する_30(元満了日);
      const 注意 = GF_車検注意を判定する_30(元満了日, 今);

      let 次 = 予定索引.get(id);

      if (!次) {
        次 = 満了日
          ? {
              予定: 注意 === '⚠ 車検満了（期限超過）'
                ? '⚠ 車検満了（期限超過）'
                : '車検満了',
              日付: 満了日
            }
          : { 予定: '', 日付: '' };
      }

      const 値 = [
        次.予定,
        次.日付,
        元満了日 || '',
        注意
      ];

      値.forEach((v, j) => {
        書込列[j][i] = [v];
      });

      件数++;
    });

    列名.forEach((name, j) => {
      状況
        .getRange(2, 表示.列[name] + 1, 表示.行.length, 1)
        .setValues(書込列[j]);
    });

    SpreadsheetApp.flush();
    console.log('車検表示の一括更新完了：' + 件数 + '台');

  } finally {
    lock.releaseLock();
  }
}