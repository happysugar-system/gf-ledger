/************************************************************

 * 車両同期キューを順番に処理

 ************************************************************/

function 車両同期キューを処理する_() {

  const props =

    PropertiesService.getScriptProperties();

  // ==========================================

  // キュー処理がすでに動いているか確認

  //

  // ScriptLockは使わない。

  // 本体同期のロックと競合させないため。

  // ==========================================

  const 実行中キー =

    'GOLD_FIRST_車両同期キュー実行中';

  const 今 =

    new Date().getTime();

  const 実行中時刻 =

    Number(

      props.getProperty(実行中キー) || 0

    );

  // 10分以内なら別の処理が動いていると判断

  if (

    実行中時刻 &&

    今 - 実行中時刻 < 10 * 60 * 1000

  ) {

    return;

  }

  // 自分が処理担当になる

  props.setProperty(

    実行中キー,

    String(今)

  );

  try {

    while (true) {

      // ========================================

      // 現在待っている車両を全部取得

      // ========================================

      const all =

        props.getProperties();

      const prefix =

        'GOLD_FIRST_車両同期待ち_';

      const 待ち一覧 =

        Object.keys(all)

          .filter(

            key => key.indexOf(prefix) === 0

          )

          .map(key => {

            try {

              const data =

                JSON.parse(all[key]);

              return {

                key: key,

                row: Number(data.row),

                現在使用者変更:

                  Boolean(

                    data.現在使用者変更

                  ),

                更新時刻:

                  Number(

                    data.更新時刻 || 0

                  )

              };

            } catch (e) {

              return null;

            }

          })

          .filter(

            x =>

              x &&

              x.row >= 2

          )

          // 入力された順番に処理

          .sort(

            (a, b) =>

              a.更新時刻 - b.更新時刻

          );

      // ========================================

      // もう待ちがなければ終了

      // ========================================

      if (!待ち一覧.length) {

        break;

      }

      const item =

        待ち一覧[0];

      // ========================================

      // 処理前に今回分をキューから削除

      //

      // 同期中に同じ行がもう一度編集されたら

      // 新しいキューとして再登録される

      // ========================================

      props.deleteProperty(

        item.key

      );

      try {

        車両台帳の1台を同期する(

          item.row,

          item.現在使用者変更

        );

      } catch (err) {

        console.error(

          '車両同期キュー失敗 / 行=' +

          item.row +

          ' / ' +

          (

            err && err.message

              ? err.message

              : err

          )

        );

      }

      // ========================================

      // 生存確認

      //

      // 長い処理になっても

      // 「実行中」の時刻を更新しておく

      // ========================================

      props.setProperty(

        実行中キー,

        String(new Date().getTime())

      );

    }

  } finally {

    // ==========================================

    // 自分の処理が終了

    // ==========================================

    props.deleteProperty(

      実行中キー

    );

  }

}

