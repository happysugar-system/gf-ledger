/**

 * 車番を指定して車両台帳の1行を同期する。

 * 車番は検索入口としてのみ使用し、

 * 同期後はVehicleIDを主キーとして扱う。

 */

function 車番から車両を同期する_(車番) {

  const スプレッドシート = 対象スプレッドシートを開く_();

  const 車両台帳 = スプレッドシート.getSheetByName(シート名.車両台帳);

  if (!車両台帳) {

    throw new Error('「車両台帳」シートがありません。');

  }

  const 車番列 = 列番号を取得する_(車両台帳, '車番');

  const 最終行 = 車両台帳.getLastRow();

  if (最終行 < 2) {

    throw new Error('車両台帳にデータがありません。');

  }

  const 車番一覧 = 車両台帳

    .getRange(2, 車番列, 最終行 - 1, 1)

    .getDisplayValues()

    .flat()

    .map(v => String(v || '').trim());

  const 対象車番 = String(車番 || '').trim();

  const 一致行 = [];

  車番一覧.forEach((値, i) => {

    if (値 === 対象車番) 一致行.push(i + 2);

  });

  if (一致行.length === 0) {

    throw new Error('車番「' + 対象車番 + '」が車両台帳に見つかりません。');

  }

  if (一致行.length > 1) {

    throw new Error(

      '車番「' + 対象車番 + '」が車両台帳に複数あります。' +

      '重複を解消してから同期してください。'

    );

  }

  return 車両台帳の1台を同期する(一致行[0]);

}

