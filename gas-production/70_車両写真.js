/******************************************************
 * 車番から日付フォルダを準備
 ******************************************************/

function 車番の車両状態日付フォルダを準備する_(車番, 撮影日) {

  const ロック = LockService.getScriptLock();
  ロック.waitLock(30000);

  try {

    const スプレッドシート =
      対象スプレッドシートを開く_();

    const 車両台帳 =
      必須シートを取得する_(
        スプレッドシート,
        シート名.車両台帳
      );

    const 車番列 =
      列番号を取得する_(
        車両台帳,
        '車番'
      );

    const 最終行 =
      車両台帳.getLastRow();

    if (最終行 < 2) {
      throw new Error(
        '車両台帳にデータがありません。'
      );
    }

    const 対象車番 =
      String(車番 || '').trim();

    const 車番一覧 =
      車両台帳
        .getRange(
          2,
          車番列,
          最終行 - 1,
          1
        )
        .getDisplayValues()
        .flat()
        .map(
          v => String(v || '').trim()
        );

    const 一致行 = [];

    車番一覧.forEach(
      (値, i) => {

        if (値 === 対象車番) {
          一致行.push(i + 2);
        }

      }
    );

    if (一致行.length === 0) {

      throw new Error(
        '車番「' +
        対象車番 +
        '」が車両台帳に見つかりません。'
      );
    }

    if (一致行.length > 1) {

      throw new Error(
        '車番「' +
        対象車番 +
        '」が車両台帳に複数あります。'
      );
    }

    return 車両行の車両状態日付フォルダを準備する_(
      一致行[0],
      撮影日
    );

  } finally {

    ロック.releaseLock();

  }
}


/******************************************************
 * 車両台帳の行から日付フォルダを準備
 ******************************************************/

function 車両行の車両状態日付フォルダを準備する_(
  行番号,
  撮影日
) {

  const スプレッドシート =
    対象スプレッドシートを開く_();

  const 車両台帳 =
    必須シートを取得する_(
      スプレッドシート,
      シート名.車両台帳
    );

  const 車両状況 =
    必須シートを取得する_(
      スプレッドシート,
      シート名.車両状況
    );

  const 車両データ =
    行データを取得する_(
      車両台帳,
      行番号
    );

  const VehicleID =
    String(
      車両データ['VehicleID'] || ''
    ).trim();

  const 車番 =
    String(
      車両データ['車番'] || ''
    ).trim();

  if (!VehicleID) {

    throw new Error(
      'VehicleIDがありません。先に車両同期を実行してください。'
    );
  }

  if (!車番) {

    throw new Error(
      '車番がありません。'
    );
  }


  /****************************************************
   * 撮影日
   ****************************************************/

  const 日付 =
    正しい日付にする_(
      撮影日
    );

  const 日付名 =
    Utilities.formatDate(
      日付,
      Session.getScriptTimeZone(),
      'yyyy-MM-dd'
    );


  /****************************************************
   * Drive
   ****************************************************/

  const 親フォルダ =
    Drive親フォルダを取得する_();

  const 車両ルート =
    子フォルダを取得または作成する_(
      親フォルダ,
      '01_車両'
    );

  const 車両フォルダ =
    ID付きフォルダを取得または作成する_(
      車両ルート,
      VehicleID,
      車番
    );

  const 車両状態親フォルダ =
    子フォルダを取得または作成する_(
      車両フォルダ,
      '車両状態画像'
    );

  // 同じ日なら既存フォルダを再利用
  const 日付フォルダ =
    子フォルダを取得または作成する_(
      車両状態親フォルダ,
      日付名
    );


  /****************************************************
   * 車両台帳
   ****************************************************/

  セルを書き込む_(
    車両台帳,
    行番号,
    '車両フォルダ',
    車両フォルダ.getUrl()
  );


  /****************************************************
   * 最新／前回リンク更新
   ****************************************************/

  車両状態フォルダリンクを更新する_(
    スプレッドシート,
    車両状況,
    VehicleID,
    車両状態親フォルダ
  );

  SpreadsheetApp.flush();


  return {

    VehicleID: VehicleID,

    車番: 車番,

    撮影日: 日付名,

    日付フォルダID:
      日付フォルダ.getId(),

    日付フォルダURL:
      日付フォルダ.getUrl()

  };
}


/******************************************************
 * 写真保存本体
 *
 * 80_スマホ画面.gs から呼ばれる
 ******************************************************/

function 車両状態写真を保存する_(
  VehicleID,
  写真Blob一覧,
  撮影日
) {

  const ロック =
    LockService.getScriptLock();

  ロック.waitLock(30000);

  try {

    const 対象VehicleID =
      String(
        VehicleID || ''
      ).trim();

    if (!対象VehicleID) {

      throw new Error(
        'VehicleIDが空です。'
      );
    }

    if (
      !Array.isArray(写真Blob一覧) ||
      写真Blob一覧.length === 0
    ) {

      throw new Error(
        '保存する写真がありません。'
      );
    }


    /**************************************************
     * 車両台帳
     **************************************************/

    const スプレッドシート =
      対象スプレッドシートを開く_();

    const 車両台帳 =
      必須シートを取得する_(
        スプレッドシート,
        シート名.車両台帳
      );

    const 行番号 =
      IDで行を探す_(
        車両台帳,
        'VehicleID',
        対象VehicleID
      );

    if (!行番号) {

      throw new Error(
        'VehicleID=' +
        対象VehicleID +
        ' が車両台帳に見つかりません。'
      );
    }


    /**************************************************
     * 保存フォルダ準備
     **************************************************/

    const 準備結果 =
      車両行の車両状態日付フォルダを準備する_(
        行番号,
        撮影日 || new Date()
      );

    const 日付フォルダ =
      DriveApp.getFolderById(
        準備結果.日付フォルダID
      );


    /**************************************************
     * 写真保存
     **************************************************/

    const 保存済み = [];

    写真Blob一覧.forEach(
      (Blob, i) => {

        if (!Blob) return;

        const 元ファイル名 =
          String(
            Blob.getName
              ? Blob.getName()
              : ''
          ).trim();

        const 拡張子 =
          拡張子を取得する_(
            元ファイル名
          );

        const ファイル名 =
          準備結果.撮影日 +
          '_' +
          String(i + 1)
            .padStart(2, '0') +
          (
            拡張子
              ? '.' + 拡張子
              : ''
          );

        const 作成ファイル =
          日付フォルダ.createFile(
            Blob
              .copyBlob()
              .setName(
                ファイル名
              )
          );

        保存済み.push({

          ファイルID:
            作成ファイル.getId(),

          ファイル名:
            作成ファイル.getName(),

          URL:
            作成ファイル.getUrl()

        });

      }
    );


    if (保存済み.length === 0) {

      throw new Error(
        '写真を1枚も保存できませんでした。'
      );
    }


    /**************************************************
     * 保存後もう一度リンク更新
     **************************************************/

    const 車両状況 =
      必須シートを取得する_(
        スプレッドシート,
        シート名.車両状況
      );

    const 車両データ =
      行データを取得する_(
        車両台帳,
        行番号
      );

    const 車番 =
      String(
        車両データ['車番'] || ''
      ).trim();

    const 親フォルダ =
      Drive親フォルダを取得する_();

    const 車両ルート =
      子フォルダを取得または作成する_(
        親フォルダ,
        '01_車両'
      );

    const 車両フォルダ =
      ID付きフォルダを取得または作成する_(
        車両ルート,
        対象VehicleID,
        車番
      );

    const 車両状態親フォルダ =
      子フォルダを取得または作成する_(
        車両フォルダ,
        '車両状態画像'
      );

    車両状態フォルダリンクを更新する_(
      スプレッドシート,
      車両状況,
      対象VehicleID,
      車両状態親フォルダ
    );

    SpreadsheetApp.flush();


    return {

      VehicleID:
        対象VehicleID,

      撮影日:
        準備結果.撮影日,

      日付フォルダURL:
        準備結果.日付フォルダURL,

      保存枚数:
        保存済み.length,

      ファイル:
        保存済み

    };

  } finally {

    ロック.releaseLock();

  }
}


/******************************************************
 * 最新／前回フォルダリンク更新
 ******************************************************/

function 車両状態フォルダリンクを更新する_(
  スプレッドシート,
  車両状況,
  VehicleID,
  車両状態親フォルダ
) {


  /****************************************************
   * 日付フォルダを取得
   ****************************************************/

  const フォルダ一覧 =
    車両状態親フォルダ.getFolders();

  const 日付フォルダ一覧 = [];

  while (フォルダ一覧.hasNext()) {

    const フォルダ =
      フォルダ一覧.next();

    const 名前 =
      String(
        フォルダ.getName() || ''
      ).trim();

    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(
        名前
      )
    ) {
      continue;
    }

    const 日付 =
      日付文字列をDateにする_(
        名前
      );

    if (!日付) continue;

    日付フォルダ一覧.push({

      名前: 名前,

      日付: 日付,

      URL:
        フォルダ.getUrl()

    });
  }


  /****************************************************
   * 新しい日付順
   ****************************************************/

  日付フォルダ一覧.sort(
    (a, b) =>
      b.日付.getTime() -
      a.日付.getTime()
  );

  const 最新 =
    日付フォルダ一覧.length >= 1
      ? 日付フォルダ一覧[0]
      : null;

  const 前回 =
    日付フォルダ一覧.length >= 2
      ? 日付フォルダ一覧[1]
      : null;


  /****************************************************
   * 車両状況
   ****************************************************/

  const 車両状況行 =
    IDで行を探す_(
      車両状況,
      'VehicleID',
      VehicleID
    );

  if (!車両状況行) {

    throw new Error(
      'VehicleID=' +
      VehicleID +
      ' が車両状況にありません。'
    );
  }

  セルを書き込む_(
    車両状況,
    車両状況行,
    '📷車両状態フォルダ',
    最新 ? 最新.URL : ''
  );

  セルを書き込む_(
    車両状況,
    車両状況行,
    '📷前回車両状態フォルダ',
    前回 ? 前回.URL : ''
  );

  セルを書き込む_(
    車両状況,
    車両状況行,
    '更新日時',
    new Date()
  );


  /****************************************************
   * 利用者管理
   ****************************************************/

  const 利用者管理 =
    必須シートを取得する_(
      スプレッドシート,
      シート名.利用者管理
    );

  let 利用者管理行 =
    IDで行を探す_(
      利用者管理,
      'VehicleID',
      VehicleID
    );


  /****************************************************
   * 利用者管理に行がなければ作る
   ****************************************************/

  if (!利用者管理行) {

    const 車両台帳 =
      必須シートを取得する_(
        スプレッドシート,
        シート名.車両台帳
      );

    const 車両台帳行 =
      IDで行を探す_(
        車両台帳,
        'VehicleID',
        VehicleID
      );

    if (!車両台帳行) {

      throw new Error(
        'VehicleID=' +
        VehicleID +
        ' が車両台帳にありません。'
      );
    }

    const 車両データ =
      行データを取得する_(
        車両台帳,
        車両台帳行
      );

    利用者管理を更新する_(
      利用者管理,
      車両データ
    );

    利用者管理行 =
      IDで行を探す_(
        利用者管理,
        'VehicleID',
        VehicleID
      );
  }


  /****************************************************
   * 利用者管理へ最新／前回を反映
   ****************************************************/

  if (利用者管理行) {

    セルを書き込む_(
      利用者管理,
      利用者管理行,
      '最新 車両状態写真',
      最新 ? 最新.URL : ''
    );

    セルを書き込む_(
      利用者管理,
      利用者管理行,
      '前回 車両状態写真',
      前回 ? 前回.URL : ''
    );

    セルを書き込む_(
      利用者管理,
      利用者管理行,
      '更新日時',
      new Date()
    );

  } else {

    throw new Error(
      '利用者管理にVehicleID=' +
      VehicleID +
      ' の行を作成できませんでした。'
    );
  }

  SpreadsheetApp.flush();

  console.log(
    '車両状態リンク更新完了 / ' +
    VehicleID +
    ' / 最新=' +
    (最新 ? 最新.名前 : 'なし') +
    ' / 前回=' +
    (前回 ? 前回.名前 : 'なし')
  );
}


/******************************************************
 * 日付処理
 ******************************************************/

function 正しい日付にする_(値) {

  let 日付;

  if (値 instanceof Date) {

    日付 =
      new Date(
        値.getTime()
      );

  } else if (
    typeof 値 === 'string' &&
    値.trim()
  ) {

    const 文字列 =
      値.trim();

    const 一致 =
      文字列.match(
        /^(\d{4})[-\/](\d{1,2})[-\/](\d{1,2})$/
      );

    if (一致) {

      日付 =
        new Date(
          Number(一致[1]),
          Number(一致[2]) - 1,
          Number(一致[3])
        );

    } else {

      日付 =
        new Date(
          文字列
        );
    }

  } else {

    日付 =
      new Date();
  }

  if (
    isNaN(
      日付.getTime()
    )
  ) {

    throw new Error(
      '撮影日が正しくありません。'
    );
  }

  日付.setHours(
    0,
    0,
    0,
    0
  );

  return 日付;
}


function 日付文字列をDateにする_(文字列) {

  const 一致 =
    String(
      文字列 || ''
    ).match(
      /^(\d{4})-(\d{2})-(\d{2})$/
    );

  if (!一致) {
    return null;
  }

  const 日付 =
    new Date(
      Number(一致[1]),
      Number(一致[2]) - 1,
      Number(一致[3])
    );

  if (
    isNaN(
      日付.getTime()
    )
  ) {
    return null;
  }

  // 2026-02-31などを除外
  if (
    日付.getFullYear() !==
      Number(一致[1]) ||
    日付.getMonth() !==
      Number(一致[2]) - 1 ||
    日付.getDate() !==
      Number(一致[3])
  ) {

    return null;
  }

  日付.setHours(
    0,
    0,
    0,
    0
  );

  return 日付;
}


/******************************************************
 * ファイル拡張子
 ******************************************************/

function 拡張子を取得する_(ファイル名) {

  const 名前 =
    String(
      ファイル名 || ''
    ).trim();

  const 位置 =
    名前.lastIndexOf('.');

  if (
    位置 <= 0 ||
    位置 === 名前.length - 1
  ) {

    return '';
  }

  return 名前
    .substring(
      位置 + 1
    )
    .toLowerCase();
}


/******************************************************
 * 診断テスト
 ******************************************************/

function 車両写真リンク診断テスト() {

  const ss =
    対象スプレッドシートを開く_();

  const 利用者 =
    必須シートを取得する_(
      ss,
      シート名.利用者管理
    );

  const 状況 =
    必須シートを取得する_(
      ss,
      シート名.車両状況
    );

  const 最終行 =
    利用者.getLastRow();

  if (最終行 < 2) {

    throw new Error(
      '利用者管理にデータがありません。'
    );
  }

  const VehicleID列 =
    列番号を取得する_(
      利用者,
      'VehicleID'
    );

  const 最新列 =
    列番号を取得する_(
      利用者,
      '最新 車両状態写真'
    );

  const 前回列 =
    列番号を取得する_(
      利用者,
      '前回 車両状態写真'
    );

  const 結果 = [];

  for (
    let 行 = 2;
    行 <= 最終行;
    行++
  ) {

    const VehicleID =
      String(
        利用者
          .getRange(
            行,
            VehicleID列
          )
          .getDisplayValue() ||
        ''
      ).trim();

    if (!VehicleID) continue;

    const 状況行 =
      IDで行を探す_(
        状況,
        'VehicleID',
        VehicleID
      );

    if (!状況行) continue;

    const 最新状況列 =
      列番号を取得する_(
        状況,
        '📷車両状態フォルダ'
      );

    const 前回状況列 =
      列番号を取得する_(
        状況,
        '📷前回車両状態フォルダ'
      );

    const 最新Rich =
      状況
        .getRange(
          状況行,
          最新状況列
        )
        .getRichTextValue();

    const 前回Rich =
      状況
        .getRange(
          状況行,
          前回状況列
        )
        .getRichTextValue();

    const 最新URL =
      最新Rich &&
      最新Rich.getLinkUrl()
        ? 最新Rich.getLinkUrl()
        : '';

    const 前回URL =
      前回Rich &&
      前回Rich.getLinkUrl()
        ? 前回Rich.getLinkUrl()
        : '';

    結果.push({

      VehicleID: VehicleID,

      利用者管理行: 行,

      車両状況行: 状況行,

      最新URL: 最新URL,

      前回URL: 前回URL,

      利用者管理_最新現在値:
        利用者
          .getRange(
            行,
            最新列
          )
          .getDisplayValue(),

      利用者管理_前回現在値:
        利用者
          .getRange(
            行,
            前回列
          )
          .getDisplayValue()

    });
  }

  console.log(
    JSON.stringify(
      結果,
      null,
      2
    )
  );

  return JSON.stringify(
    結果,
    null,
    2
  );
}


