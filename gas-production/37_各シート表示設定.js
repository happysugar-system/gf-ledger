/************************************************************
 * 共通表示
 ************************************************************/

function 表示共通設定_(sheet, ヘッダー色) {

  const 最終列 = sheet.getLastColumn();
  const 最大行 = sheet.getMaxRows();

  if (最終列 < 1) return;


  // ==========================================
  // 固定
  // ==========================================

  sheet.setFrozenRows(1);


  // ==========================================
  // ヘッダー
  // ==========================================

  sheet
    .getRange(1, 1, 1, 最終列)
    .setBackground(ヘッダー色)
    .setFontWeight('bold')
    .setFontColor('#333333')
    .setHorizontalAlignment('center')
    .setVerticalAlignment('middle')
    .setWrap(true);

  sheet.setRowHeight(1, 42);


  // ==========================================
  // データ部分
  // ==========================================

  if (最大行 >= 2) {

    const データ範囲 =
      sheet.getRange(
        2,
        1,
        最大行 - 1,
        最終列
      );

    データ範囲
      .setVerticalAlignment('middle')
      .setFontColor('#333333');
  }


  // ==========================================
  // ★薄いグレーの罫線
  // ==========================================

  const 全体範囲 =
    sheet.getRange(
      1,
      1,
      最大行,
      最終列
    );

  全体範囲.setBorder(
    true,   // 上
    true,   // 左
    true,   // 下
    true,   // 右
    true,   // 縦
    true,   // 横
    '#D9D9D9',
    SpreadsheetApp.BorderStyle.SOLID
  );


  // ==========================================
  // フィルター
  // ==========================================

  if (!sheet.getFilter()) {

    const 行数 =
      Math.max(sheet.getLastRow(), 2);

    sheet
      .getRange(
        1,
        1,
        行数,
        最終列
      )
      .createFilter();
  }
}


/************************************************************
 * 列幅
 ************************************************************/

function 列幅を設定する_(sheet, 設定) {

  Object.keys(設定).forEach(列名 => {

    const 列 =
      列番号を取得する_(sheet, 列名);

    if (!列) return;

    sheet.setColumnWidth(
      列,
      設定[列名]
    );
  });
}


/************************************************************
 * 管理用ID列を非表示
 ************************************************************/

function 列を非表示にする_(sheet, 列名一覧) {

  列名一覧.forEach(列名 => {

    const 列 =
      列番号を取得する_(sheet, 列名);

    if (!列) return;

    sheet.hideColumns(列);
  });
}

/************************************************************
 * メールアドレス自動リンク
 *
 * 対象：
 * ・車両台帳
 * ・ドライバーマスター
 *
 * メールアドレスを入力・変更したセルだけ処理する
 ************************************************************/

function GOLD_FIRSTメールリンク自動設定(e) {

  if (!e || !e.range) return;

  const range = e.range;
  const sheet = range.getSheet();

  const sheetName = sheet.getName();

  // 対象シートだけ
  const 対象シート = [
    シート名.車両台帳,
    シート名.ドライバーマスター
  ];

  if (!対象シート.includes(sheetName)) return;

  // ヘッダー行は処理しない
  if (range.getRow() <= 1) return;


  // 対象メール列
  const メール列名 = [
    '契約者メールアドレス',
    '緊急連絡先メールアドレス'
  ];

  const 編集開始列 = range.getColumn();
  const 編集終了列 =
    編集開始列 + range.getNumColumns() - 1;

  メール列名.forEach(列名 => {

    const 列 =
      列番号を取得する_(sheet, 列名);

    if (!列) return;

    // 今回編集した範囲にメール列が含まれていなければ終了
    if (
      列 < 編集開始列 ||
      列 > 編集終了列
    ) {
      return;
    }

    const 開始行 =
      Math.max(range.getRow(), 2);

    const 終了行 =
      range.getLastRow();

    const 行数 =
      終了行 - 開始行 + 1;

    if (行数 <= 0) return;

    const 対象範囲 =
      sheet.getRange(
        開始行,
        列,
        行数,
        1
      );

    const values =
      対象範囲.getDisplayValues();

    const richValues =
      values.map(([value]) => {

        const email =
          String(value || '').trim();

        let builder =
          SpreadsheetApp
            .newRichTextValue()
            .setText(email);

        if (email) {

          builder =
            builder.setLinkUrl(
              'mailto:' + email
            );
        }

        return [builder.build()];
      });

    対象範囲.setRichTextValues(
      richValues
    );
  });
}

function GOLD_FIRSTメールリンクトリガーを設定する() {

  const ss = 対象スプレッドシートを開く_();

  const 関数名 = 'GOLD_FIRSTメールリンク自動設定';

  // 同じトリガーがあれば一旦削除
  ScriptApp.getProjectTriggers().forEach(trigger => {

    if (
      trigger.getHandlerFunction() === 関数名
    ) {
      ScriptApp.deleteTrigger(trigger);
    }
  });

  // 対象スプレッドシート専用の編集トリガーを作成
  ScriptApp
    .newTrigger(関数名)
    .forSpreadsheet(ss)
    .onEdit()
    .create();

  return 'メールリンク自動設定トリガーを作成しました。';
}
/**
 * URLが入っているセルを、
 * 「○○を見る」という分かりやすいリンク表示にする。
 *
 * URL自体やDriveフォルダは変更しない。
 */
function フォルダリンク表示名を整える_(シート, 列名, 表示名) {

  const 列番号 = 列番号を取得する_(シート, 列名);

  if (!列番号) return;

  const 最終行 = シート.getLastRow();

  if (最終行 < 2) return;

  for (let 行 = 2; 行 <= 最終行; 行++) {

    const セル = シート.getRange(行, 列番号);

    // 通常の値として入っているURLを取得
    let url = String(セル.getValue() || '').trim();

    // すでにRichTextリンクになっている場合もURLを拾う
    const richText = セル.getRichTextValue();

    if (richText) {
      const richUrl = richText.getLinkUrl();
      if (richUrl) {
        url = richUrl;
      }
    }

    if (!url) continue;

    // URLではない値は触らない
    if (!/^https?:\/\//i.test(url)) continue;

    const 新しい表示 = SpreadsheetApp
      .newRichTextValue()
      .setText(表示名)
      .setLinkUrl(url)
      .build();

    セル.setRichTextValue(新しい表示);
  }
}


